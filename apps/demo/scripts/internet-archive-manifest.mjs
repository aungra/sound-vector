import fs from "node:fs";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "../../..");
const TRAINING_DIR = path.join(ROOT, "genre-training");
const CACHE_PATHS_PATH = path.join(TRAINING_DIR, "cache-paths.local.json");
const CANDIDATES_PATH = path.join(TRAINING_DIR, "internet-archive-cc-candidates.json");
const REVIEW_TSV_PATH = path.join(TRAINING_DIR, "internet-archive-review-queue.tsv");
const MANIFEST_PATH = path.join(TRAINING_DIR, "internet-archive-cc-source-manifest.json");
const REPORT_PATH = path.join(TRAINING_DIR, "internet-archive-manifest-report.json");

const MODE = String(process.env.MMFR_IA_MANIFEST_MODE || "review").trim();
const LIMIT_PER_GENRE = Math.max(1, Number(process.env.MMFR_IA_MANIFEST_LIMIT_PER_GENRE || 50));
const MIN_SCORE = Math.max(0, Math.min(100, Number(process.env.MMFR_IA_MANIFEST_MIN_SCORE || 55)));
const DOWNLOAD_AUDIO = process.env.MMFR_IA_DOWNLOAD_AUDIO === "1";
const ACCEPT_UNREVIEWED = process.env.MMFR_IA_ACCEPT_UNREVIEWED === "1";
const REQUEST_TIMEOUT_MS = Math.max(5000, Number(process.env.MMFR_IA_DOWNLOAD_TIMEOUT_MS || 120000));

const SUSPICIOUS = [
  [/\bai music\b|\bsuno ai\b|\budio\b|generated by ai|artificial intelligence/i, "ai-generated-or-ai-tagged"],
  [/collection pack|sample pack|loop pack|sound pack/i, "sample-or-collection-pack"],
  [/podcast|interview|audiobook|lecture|talk shows|monologue|radio show|sermon/i, "spoken-word"],
  [/karaoke|cover|reaction|tutorial|lesson/i, "derivative-or-non-song"],
  [/dj set|mixtape|continuous mix/i, "long-mix-or-dj-set"]
];
const MUSIC_POSITIVE = /\b(album|single|track|song|music|band|rock|punk|hardcore|house|deep house|soul|r&b|funk|trap|hip.?hop|opera|aria|classical|soundtrack|ost|j-?pop|city pop|electronic|techno|dance|jazz|reggae|dub)\b/i;
const LICENSE_BONUS = /^(CC0|CC-BY|CC-BY-SA)$/i;
const COLLECTION_NEGATIVE = /\b(compilation|charts?|playlist|collection|documental|documentary|various artists|promo|radio|podcast|show|pack|metalcast|open metalcast|funeral doom|drone)\b/i;
const GENRE_POSITIVE = {
  "アニメソング": /anime|anisong|j-?pop|japanese|soundtrack|ost|vocaloid/i,
  "オペラ": /opera|aria|soprano|tenor|baritone|libretto|classical vocal|bel.?canto/i,
  "シティ・ポップ": /city pop|future funk|japanese pop|j-?pop|kayokyoku|funk|disco|synth.?pop/i,
  "ソウルミュージック": /soul|r&b|rhythm and blues|neo soul|funk|gospel/i,
  "ディープ・ハウス": /deep house|house|club|dance|electronic|minimal/i,
  "トラップ": /trap|808|hip.?hop|rap|phonk|southern/i,
  "ハードコア": /hardcore|punk|crust|grind|metalcore|post.?hardcore/i
};

function loadJson(pathname, fallback) {
  if (!fs.existsSync(pathname)) return fallback;
  try {
    return JSON.parse(fs.readFileSync(pathname, "utf8"));
  } catch {
    return fallback;
  }
}

function slug(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90) || "audio";
}

function csvCell(value) {
  return `"${String(value ?? "").replaceAll("\"", "\"\"")}"`;
}

function parseTsvLine(line) {
  const out = [];
  let cell = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const ch = line[index];
    const next = line[index + 1];
    if (quoted) {
      if (ch === "\"" && next === "\"") {
        cell += "\"";
        index += 1;
      } else if (ch === "\"") {
        quoted = false;
      } else {
        cell += ch;
      }
    } else if (ch === "\"") {
      quoted = true;
    } else if (ch === "\t") {
      out.push(cell);
      cell = "";
    } else {
      cell += ch;
    }
  }
  out.push(cell);
  return out;
}

function existingReviewStatuses() {
  if (!fs.existsSync(REVIEW_TSV_PATH)) return new Map();
  const lines = fs.readFileSync(REVIEW_TSV_PATH, "utf8").split(/\r?\n/).filter(Boolean);
  if (lines.length < 2) return new Map();
  const header = parseTsvLine(lines[0]);
  const statusIndex = header.indexOf("reviewStatus");
  const noteIndex = header.indexOf("reviewNote");
  const identifierIndex = header.indexOf("identifier");
  if (statusIndex < 0 || identifierIndex < 0) return new Map();
  const map = new Map();
  for (const line of lines.slice(1)) {
    const cells = parseTsvLine(line);
    const identifier = cells[identifierIndex];
    if (!identifier) continue;
    map.set(identifier, {
      reviewStatus: cells[statusIndex] || "",
      reviewNote: noteIndex >= 0 ? cells[noteIndex] || "" : ""
    });
  }
  return map;
}

function suspicionReasons(item) {
  const text = [
    item.title,
    item.creator,
    item.query,
    Array.isArray(item.subject) ? item.subject.join(" ") : item.subject,
    item.candidateAudioName
  ].join(" ");
  return SUSPICIOUS.filter(([pattern]) => pattern.test(text)).map(([, reason]) => reason);
}

function recommendation(item) {
  const reasons = suspicionReasons(item);
  const quality = reviewQuality(item);
  if (reasons.length) return { value: "reject-or-review-carefully", reasons };
  if (quality.reviewPriority >= 78) return { value: "review-first", reasons: [] };
  if (quality.reviewPriority >= 60) return { value: "maybe-review", reasons: [] };
  return { value: "low-confidence-review", reasons: [] };
}

function reviewQuality(item) {
  const reasons = suspicionReasons(item);
  const subject = Array.isArray(item.subject) ? item.subject.join(" ") : String(item.subject || "");
  const text = `${item.title || ""} ${item.creator || ""} ${item.query || ""} ${subject} ${item.candidateAudioName || ""}`;
  let score = Math.max(0, Math.min(100, Number(item.matchScore || 0)));
  if (MUSIC_POSITIVE.test(text)) score += 10;
  if ((GENRE_POSITIVE[item.genre] || /$a/).test(text)) score += 14;
  if (new RegExp(String(item.genre || "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "i").test(text)) score += 12;
  if (COLLECTION_NEGATIVE.test(text)) score -= 18;
  if (LICENSE_BONUS.test(String(item.license || ""))) score += 6;
  if (/CC-BY-NC-ND|CC-BY-ND/i.test(String(item.license || ""))) score -= 4;
  score -= reasons.length * 28;
  if (/spoken-word/.test(reasons.join(" "))) score -= 28;
  if (/ai-generated/.test(reasons.join(" "))) score -= 35;
  return {
    reviewPriority: Math.max(0, Math.min(100, Math.round(score))),
    riskFlags: reasons,
    musicSignals: MUSIC_POSITIVE.test(text),
    licensePreferred: LICENSE_BONUS.test(String(item.license || ""))
  };
}

function accepted(item) {
  const status = String(item.reviewStatus || item.status || "").toLowerCase();
  return item.approved === true || status === "approved" || status === "accepted" || status === "ok";
}

function loadCandidates() {
  const payload = loadJson(CANDIDATES_PATH, { items: [] });
  return Array.isArray(payload) ? payload : payload.items || [];
}

function externalDataDir() {
  const cachePaths = loadJson(CACHE_PATHS_PATH, {});
  const configured = process.env.MMFR_EXTERNAL_DATA_DIR || cachePaths.externalDataDir || path.join(ROOT, ".external-data");
  return path.resolve(configured, "internet-archive");
}

function localAudioPath(item, baseDir) {
  const ext = path.extname(new URL(item.candidateAudioUrl).pathname) || ".mp3";
  const file = `${slug(item.identifier)}-${slug(item.candidateAudioName)}${ext}`.replace(new RegExp(`${ext.replace(".", "\\.")}${ext.replace(".", "\\.")}$`, "i"), ext);
  return path.join(baseDir, slug(item.genre), file);
}

async function download(url, outPath) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    if (fs.existsSync(outPath) && fs.statSync(outPath).size > 0) return { skipped: true };
    const response = await fetch(url, {
      signal: controller.signal,
      headers: { "User-Agent": "MUSICtee CC training data downloader; contact local project owner" }
    });
    if (!response.ok || !response.body) throw new Error(`${response.status} ${response.statusText}`);
    await pipeline(response.body, fs.createWriteStream(outPath));
    return { skipped: false };
  } finally {
    clearTimeout(timeout);
  }
}

function writeReviewQueue(candidates) {
  const previous = existingReviewStatuses();
  const header = [
    "reviewStatus",
    "reviewNote",
    "genre",
    "macroGenre",
    "matchScore",
    "reviewPriority",
    "recommendation",
    "riskFlags",
    "title",
    "creator",
    "license",
    "licenseUrl",
    "referenceUrl",
    "candidateAudioUrl",
    "subject",
    "identifier"
  ];
  const rows = candidates.map(item => {
    const rec = recommendation(item);
    const quality = reviewQuality(item);
    const previousReview = previous.get(item.identifier) || {};
    return [
      previousReview.reviewStatus || item.reviewStatus || "",
      previousReview.reviewNote || item.reviewNote || "",
      item.genre,
      item.macroGenre,
      item.matchScore,
      quality.reviewPriority,
      rec.value,
      rec.reasons.join("|"),
      item.title,
      item.creator,
      item.license,
      item.licenseUrl,
      item.referenceUrl,
      item.candidateAudioUrl,
      Array.isArray(item.subject) ? item.subject.join("; ") : item.subject,
      item.identifier
    ].map(csvCell).join("\t");
  });
  fs.writeFileSync(REVIEW_TSV_PATH, `${header.map(csvCell).join("\t")}\n${rows.join("\n")}\n`);
}

async function main() {
  const candidates = loadCandidates()
    .filter(item => item.candidateAudioUrl && item.genre && item.macroGenre && Number(item.matchScore || 0) >= MIN_SCORE)
    .sort((a, b) => a.genre.localeCompare(b.genre, "ja") || Number(b.matchScore || 0) - Number(a.matchScore || 0));
  const previousReviews = existingReviewStatuses();
  for (const item of candidates) {
    const previous = previousReviews.get(item.identifier);
    if (previous?.reviewStatus) item.reviewStatus = previous.reviewStatus;
    if (previous?.reviewNote) item.reviewNote = previous.reviewNote;
  }
  writeReviewQueue(candidates);

  const baseDir = externalDataDir();
  const counts = {};
  const selected = [];
  const rejected = [];
  for (const item of candidates) {
    const rec = recommendation(item);
    if (rec.reasons.length && !accepted(item)) {
      rejected.push({ ...item, rejectReason: rec.reasons.join("|") });
      continue;
    }
    if (!ACCEPT_UNREVIEWED && !accepted(item)) {
      rejected.push({ ...item, rejectReason: "not-reviewed" });
      continue;
    }
    counts[item.genre] = counts[item.genre] || 0;
    if (counts[item.genre] >= LIMIT_PER_GENRE) {
      rejected.push({ ...item, rejectReason: "genre-limit-reached" });
      continue;
    }
    const filePath = localAudioPath(item, baseDir);
    if (DOWNLOAD_AUDIO) {
      process.stdout.write(`${item.genre} ${item.identifier} ... `);
      try {
        const result = await download(item.candidateAudioUrl, filePath);
        console.log(result.skipped ? "exists" : "downloaded");
      } catch (error) {
        rejected.push({ ...item, rejectReason: `download-failed:${error.message}` });
        console.log(`error: ${error.message}`);
        continue;
      }
    }
    selected.push({
      source: "Internet Archive",
      sourceType: "cc-dataset",
      datasetName: "Internet Archive Creative Commons Audio",
      trackId: item.identifier,
      genre: item.genre,
      macroGenre: item.macroGenre,
      filePath,
      license: item.license,
      licenseUrl: item.licenseUrl,
      referenceUrl: item.referenceUrl,
      canonicalArtist: item.creator,
      canonicalTitle: item.title,
      internetArchiveIdentifier: item.identifier,
      originalAudioUrl: item.candidateAudioUrl,
      audioStoragePolicy: "external-local-audio; persist-features-only",
      reviewStatus: accepted(item) ? "approved" : "unreviewed-accepted-by-env"
    });
    counts[item.genre] += 1;
  }

  const manifest = {
    description: "Internet Archive CC audio manifest. Audio files must live outside the repo; review candidates before formal import.",
    generatedAt: new Date().toISOString(),
    mode: MODE,
    sourceCandidates: path.relative(ROOT, CANDIDATES_PATH),
    reviewQueue: path.relative(ROOT, REVIEW_TSV_PATH),
    audioRoot: baseDir,
    downloadAudio: DOWNLOAD_AUDIO,
    acceptUnreviewed: ACCEPT_UNREVIEWED,
    items: selected
  };
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2));
  fs.writeFileSync(REPORT_PATH, JSON.stringify({
    generatedAt: manifest.generatedAt,
    candidates: candidates.length,
    selected: selected.length,
    rejected: rejected.length,
    selectedByGenre: selected.reduce((acc, item) => {
      acc[item.genre] = (acc[item.genre] || 0) + 1;
      return acc;
    }, {}),
    rejectedByReason: rejected.reduce((acc, item) => {
      acc[item.rejectReason] = (acc[item.rejectReason] || 0) + 1;
      return acc;
    }, {}),
    rejected: rejected.slice(0, 200)
  }, null, 2));
  console.log(`Wrote ${path.relative(ROOT, REVIEW_TSV_PATH)}`);
  console.log(`Wrote ${path.relative(ROOT, MANIFEST_PATH)} (${selected.length} manifest rows)`);
  console.log(`Wrote ${path.relative(ROOT, REPORT_PATH)}`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
