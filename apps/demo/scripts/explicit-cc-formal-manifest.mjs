import fs from "node:fs";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "../../..");
const TRAINING_DIR = path.join(ROOT, "genre-training");
const CACHE_PATHS_PATH = path.join(TRAINING_DIR, "cache-paths.local.json");
const OUTPUT_PATH = path.join(TRAINING_DIR, "explicit-cc-formal-source-manifest.json");
const REPORT_PATH = path.join(TRAINING_DIR, "explicit-cc-formal-report.json");
const DOWNLOAD_AUDIO = process.env.MMFR_EXPLICIT_CC_DOWNLOAD_AUDIO === "1";
const LIMIT_PER_GENRE = Math.max(1, Number(process.env.MMFR_EXPLICIT_CC_LIMIT_PER_GENRE || 30));
const REQUEST_TIMEOUT_MS = Math.max(5000, Number(process.env.MMFR_EXPLICIT_CC_DOWNLOAD_TIMEOUT_MS || 120000));
const ALLOWED_LICENSES = new Set(["CC0", "CC-BY", "CC-BY-SA"]);

const SOURCES = [
  {
    name: "Internet Archive",
    path: path.join(TRAINING_DIR, "internet-archive-cc-candidates.json"),
    itemUrlKey: "candidateAudioUrl"
  },
  {
    name: "Wikimedia Commons",
    path: path.join(TRAINING_DIR, "wikimedia-commons-audio-candidates.json"),
    itemUrlKey: "candidateAudioUrl"
  }
];

function loadJson(pathname, fallback) {
  if (!fs.existsSync(pathname)) return fallback;
  try {
    return JSON.parse(fs.readFileSync(pathname, "utf8"));
  } catch {
    return fallback;
  }
}

function slug(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 110) || "audio";
}

function normalizeLicense(value) {
  const text = String(value || "").toUpperCase();
  if (/CC0|PUBLIC DOMAIN/.test(text)) return "CC0";
  if (/CC-BY-NC|CC-BY-ND|NONCOMMERCIAL|NO.?DERIV/.test(text)) return text.trim();
  if (/CC-BY-SA|ATTRIBUTION-SHAREALIKE/.test(text)) return "CC-BY-SA";
  if (/CC-BY\b|ATTRIBUTION 3|ATTRIBUTION 4/.test(text)) return "CC-BY";
  return text.trim();
}

function sourceItems() {
  return SOURCES.flatMap(source => {
    const payload = loadJson(source.path, { items: [] });
    const items = Array.isArray(payload) ? payload : payload.items || [];
    return items.map(item => ({
      ...item,
      source: source.name,
      sourceCandidatePath: path.relative(ROOT, source.path),
      candidateAudioUrl: item[source.itemUrlKey] || item.candidateAudioUrl
    }));
  });
}

function textFor(item) {
  const subject = Array.isArray(item.subject) ? item.subject.join(" ") : String(item.subject || "");
  return [
    item.genre,
    item.title,
    item.creator,
    item.description,
    item.candidateAudioName,
    subject
  ].join(" ").toLowerCase();
}

function hasBadSignal(text) {
  return /\b(ai music|suno ai|udio|generated by ai|podcast|interview|lecture|monologue|talk shows|spoken|lingua libre|pronunciation|inleiding|mixtape|dj set|continuous mix|sample packs?|loop packs?|collection packs?|compilation|various artists|open metalcast|metalcast|definitive .*volume|230 diverse mp3s|karaoke|cover|reaction|tutorial)\b/i.test(text);
}

function explicitEvidence(item) {
  const text = textFor(item);
  if (hasBadSignal(text)) return null;
  const license = normalizeLicense(item.license);
  if (!ALLOWED_LICENSES.has(license)) return null;

  if (item.genre === "トラップ") {
    if (/\btrap\b|\btrap[-\s]?pop\b|\btrapbed\b|\b808 beat\b|\b808\b/.test(text) && !/\btrappor\b|\btrappeur\b|\bstrap\b|\btrapped\b|\btrapdoor\b/.test(text)) {
      return "explicit trap/808 wording in title, description, tags, or filename";
    }
  }

  if (item.genre === "アニメソング") {
    if (/\banime\b|\banisong\b|\banime ost\b|\banime soundtrack\b|\botaku\b|\bvocaloid\b|japanese .*song|jp themesong/.test(text)) {
      return "explicit anime/anison/vocaloid/otaku-theme wording in metadata";
    }
  }

  if (item.genre === "シティ・ポップ") {
    if (/\bcity pop\b/.test(text) && !/lingua libre|pronunciation|speaker:/.test(text)) {
      return "explicit city pop wording in metadata";
    }
  }

  return null;
}

function stableId(item) {
  return item.identifier || item.trackId || item.title || item.referenceUrl || item.candidateAudioUrl;
}

function externalBaseDir() {
  const cachePaths = loadJson(CACHE_PATHS_PATH, {});
  const configured = process.env.MMFR_EXTERNAL_DATA_DIR || cachePaths.externalDataDir || path.join(ROOT, ".external-data");
  return path.resolve(configured, "explicit-cc-formal");
}

function localAudioPath(item, baseDir) {
  const urlPath = new URL(item.candidateAudioUrl).pathname;
  const ext = path.extname(urlPath) || ".audio";
  return path.join(baseDir, slug(item.genre), `${slug(`${item.source}-${stableId(item)}`)}${ext}`);
}

async function download(url, outPath) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    if (fs.existsSync(outPath) && fs.statSync(outPath).size > 0) return { skipped: true };
    const response = await fetch(url, {
      signal: controller.signal,
      headers: { "User-Agent": "MUSICtee explicit CC formal training downloader; contact local project owner" }
    });
    if (!response.ok || !response.body) throw new Error(`${response.status} ${response.statusText}`);
    await pipeline(response.body, fs.createWriteStream(outPath));
    return { skipped: false };
  } finally {
    clearTimeout(timeout);
  }
}

function selectItems() {
  const targets = new Set(["シティ・ポップ", "アニメソング", "トラップ"]);
  const seen = new Set();
  const selected = [];
  const rejected = [];
  for (const item of sourceItems()) {
    if (!targets.has(item.genre) || !item.candidateAudioUrl) continue;
    const evidence = explicitEvidence(item);
    const key = `${item.genre}:${item.candidateAudioUrl}`;
    if (!evidence) {
      rejected.push({ ...item, rejectReason: "insufficient-explicit-label-or-license" });
      continue;
    }
    if (seen.has(key)) continue;
    seen.add(key);
    selected.push({ ...item, labelEvidence: evidence, normalizedLicense: normalizeLicense(item.license) });
  }

  const counts = {};
  const limited = selected
    .sort((a, b) => a.genre.localeCompare(b.genre, "ja") || Number(b.matchScore || 0) - Number(a.matchScore || 0))
    .filter(item => {
      counts[item.genre] = counts[item.genre] || 0;
      if (counts[item.genre] >= LIMIT_PER_GENRE) return false;
      counts[item.genre] += 1;
      return true;
    });

  return { selected: limited, rejected };
}

async function main() {
  const baseDir = externalBaseDir();
  const { selected, rejected } = selectItems();
  const items = [];
  const downloadErrors = [];

  for (const item of selected) {
    const filePath = localAudioPath(item, baseDir);
    if (DOWNLOAD_AUDIO) {
      process.stdout.write(`${item.genre} ${item.title || stableId(item)} ... `);
      try {
        const result = await download(item.candidateAudioUrl, filePath);
        console.log(result.skipped ? "exists" : "downloaded");
      } catch (error) {
        downloadErrors.push({ genre: item.genre, title: item.title, url: item.candidateAudioUrl, error: error.message });
        console.log(`error: ${error.message}`);
        continue;
      }
    }
    items.push({
      source: item.source,
      sourceType: "cc-dataset",
      datasetName: `${item.source} explicit CC formal candidates`,
      trackId: `${slug(item.source)}-${slug(stableId(item))}`,
      genre: item.genre,
      macroGenre: item.macroGenre,
      trainingRole: "fine",
      filePath,
      sourceUrl: filePath,
      originalAudioUrl: item.candidateAudioUrl,
      referenceUrl: item.referenceUrl,
      license: item.normalizedLicense,
      licenseUrl: item.licenseUrl || item.referenceUrl,
      canonicalArtist: item.creator || item.source,
      canonicalTitle: item.title || item.candidateAudioName || stableId(item),
      labelEvidence: item.labelEvidence,
      audioStoragePolicy: "external-local-audio; persist-features-only",
      reviewStatus: "auto-approved-explicit-cc-label",
      reviewNote: "Auto-selected only when metadata contains explicit genre evidence and preferred CC license; excludes spoken, AI-tagged, mixes, and packs."
    });
  }

  const byGenre = items.reduce((acc, item) => {
    acc[item.genre] = (acc[item.genre] || 0) + 1;
    return acc;
  }, {});

  fs.writeFileSync(OUTPUT_PATH, JSON.stringify({
    description: "Strict explicit CC formal manifest for city-pop/anime-song/trap gaps. Source audio stays outside this repository; cc-import persists features only.",
    generatedAt: new Date().toISOString(),
    audioRoot: baseDir,
    labelPolicy: "Conservative auto-promotion. City-pop accepts only explicit city-pop wording; adjacent future-funk/synth-pop/retrofuture metadata is kept out of formal fine training.",
    audioStoragePolicy: "external-local-audio; persist-features-only",
    requiredFields: ["genre", "macroGenre", "filePath", "license", "licenseUrl", "referenceUrl"],
    items
  }, null, 2));

  fs.writeFileSync(REPORT_PATH, JSON.stringify({
    generatedAt: new Date().toISOString(),
    downloadAudio: DOWNLOAD_AUDIO,
    selected: selected.length,
    manifestItems: items.length,
    byGenre,
    downloadErrors,
    rejectedCount: rejected.length,
    rejectedSamples: rejected.slice(0, 50).map(item => ({
      genre: item.genre,
      title: item.title,
      source: item.source,
      license: item.license,
      referenceUrl: item.referenceUrl,
      rejectReason: item.rejectReason
    }))
  }, null, 2));

  console.log(JSON.stringify({
    output: path.relative(ROOT, OUTPUT_PATH),
    report: path.relative(ROOT, REPORT_PATH),
    audioRoot: baseDir,
    items: items.length,
    byGenre,
    downloadErrors: downloadErrors.length,
    importCommand: `MMFR_CC_MANIFEST_PATH=${path.relative(ROOT, OUTPUT_PATH)} MMFR_CC_WEAK_ONLY=0 npm --prefix apps/demo run cc-import`
  }, null, 2));
}

await main();
